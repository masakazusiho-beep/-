"""note で伸びる記事の「型」を集約したプレイブック.

製菓ジャンルで実際に伸びている投稿の傾向調査（お悩み解決・失敗の科学が
最も強い／note は読み物プラットフォームで体験談とストーリーが効く／
無料で信頼→有料で完全版、という収益導線）を、ネタ出しと本文生成の両方の
プロンプトへ注入するために切り出したもの。

方針を変えたいときは、基本ここだけを直せば ideas.py / generate.py の
両方に反映される。note_config.toml の `extra_guidance` でも上書き追記できる。
"""

from __future__ import annotations

# 記事の「柱」。上2つが実績トップ（同格で優先）、残りはバランス用。
# 2026-10時点の実測: 「失敗ばかりだった僕がお菓子の『なぜ？』を追い続けた話」
# （裏側・ストーリー型）が108ビューでスキ41＝スキ率38%と、他の失敗の科学系
# （数%台）を大きく上回った。失敗の科学だけに偏らせず、ストーリー型も
# 同じ重みで選ぶこと。
CONTENT_PILLARS = [
    "お悩み解決・失敗の科学: 「なぜ失敗するのか」「どう直すのか」を"
    "原因と理屈（温度・配合・順序など）から具体的に解く。読者の悩みを名指しで拾う。"
    "※扱う食材・失敗現象は既出記事と必ず変えること（同じ食材の言い換え再利用は禁止）。",
    "裏側・ストーリー: 作り手の視点・製菓の裏側・試行錯誤の記録。一人称の体験談"
    "（「僕が」「私が」）として書けるネタがあれば積極的に選ぶ。note ならではの"
    "『読み物』としての強みで、実績上スキ率が最も高い型。",
    "保存版・まとめ: 道具/材料/基本の『保存版』。回遊と信頼を生み、他記事への入口になる。",
    "レシピ: 単なる作り方は cookpad や動画に埋もれる。出すなら必ず"
    "『失敗しない工夫』『なぜこの手順か』をセットにして差別化する。",
]

# note で機能しやすいタイトルの型（クリック率と一覧での目立ちに効く）。
TITLE_FORMULAS = [
    "プロが教える〜 / プロだけが知っている〜",
    "〜の9割が間違える / 失敗の9割はコレが原因",
    "なぜ〜なのか｜製菓の科学",
    "〜の裏側 / お菓子屋の裏側",
    "〇〇じゃない、本当は△△（常識をひっくり返す）",
    "数字で具体化（例:『10℃違うと別物になる』『材料6つ、温度を守るだけ』）",
]

# note というメディアで戦ううえでの原則。
NOTE_PRINCIPLES = [
    "note はレシピ検索サイト（cookpad/動画）ではなく『読み物』。"
    "情報の羅列ではなく、専門性×ストーリーで最後まで読ませる。",
    "冒頭で読者の悩みや『あるある』を名指しして共感を作ってから本題へ入る。",
    "必ず独自の体験談・現場の観察を混ぜる。AI が書いた紋切り型・一般論だけにしない。",
    "記事末は必ず『次』へつなぐ: フォローする理由（次回予告）や関連記事への導線を一言添える。"
    "これが読者の定着＝伸びと収益の土台になる。",
]


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {x}" for x in items)


def idea_guidance() -> str:
    """ネタ出し（ideas.py）へ注入する戦略ガイド."""
    return "\n".join(
        [
            "【note で伸びる記事の型（この方針でネタを選ぶこと）】",
            "◆ 記事の柱（上位2つ『失敗の科学』『裏側・ストーリー』が実績トップで同格。"
            "どちらかに偏らせず、既出記事リストを見て手薄な方を選ぶこと）:",
            _bullets(CONTENT_PILLARS),
            "",
            "◆ タイトルの型（title はこのいずれかに寄せる）:",
            _bullets(TITLE_FORMULAS),
            "",
            "◆ メディア原則:",
            _bullets(NOTE_PRINCIPLES),
            "",
            "単なる『◯◯の作り方』の連発は避け、悩み解決・科学・裏側の切り口を優先すること。",
            "「〜の9割はコレが原因｜製菓の科学で解く」は1つの型にすぎない。"
            "既出記事リストでこの型が連続している場合は、別のタイトル型"
            "（プロが教える／裏側／常識をひっくり返す／数字で具体化、など）に切り替えること。",
        ]
    )


def article_guidance() -> str:
    """本文生成（generate.py）へ注入する執筆ガイド."""
    return "\n".join(
        [
            "【note で最後まで読まれる書き方】",
            "◆ メディア原則:",
            _bullets(NOTE_PRINCIPLES),
            "",
            "◆ 構成:",
            "- 冒頭: 読者の悩み・『あるある』を名指しし、共感で引き込む（一般的な前置きにしない）。",
            "- 本文: 『なぜそうなるのか』の理屈（温度・配合・順序など）と、"
            "現場ならではの具体・体験談で価値を届ける。",
            "- 結び: 読者の次の一歩と、フォロー動機になる次回予告や関連テーマへの導線を一言。",
        ]
    )
